"""
Synthetic PAD evaluation dataset generator.

Generates a clearly-labelled SYNTHETIC dataset for exercising the PAD
evaluation harness (eval/harness/run_pad_eval.py) against the heuristic
scorer. It is NOT real-world biometric evidence and MUST NOT be used to
claim production readiness.

Classes generated (per PAD-ISO-LAB-v1 sample sizes):
- BF    bona fide: textured face-like frames with inter-frame motion
- PA-01 print attack: blurred, desaturated, static frames
- PA-02 screen static: flat, glare-tinted, static frames
- PA-03 screen video (replay): flat frames with motion but low texture

Design notes:
- All frames are procedurally generated from a fixed RNG seed so runs are
  reproducible. No real faces or identities are used; subject_id values are
  synthetic labels only.
- Transformations approximate physical attack properties only coarsely
  (blur ~ print halftone loss, desaturation ~ print gamut, uniform glare
  ~ screen backlight, static frames ~ rigid media). They do NOT capture
  moire, specular highlights, color reproduction curves, depth, or real
  camera noise. Results measure harness + heuristic behavior, not
  real-world PAD performance.

Usage:
    python eval/datasets/generate_synthetic_dataset.py \
        --output-dir eval/datasets/synthetic_v1 --seed 20260826
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np

FRAME_W = 320
FRAME_H = 240
FRAMES_PER_CLIP = 12

COLLECTION_ID = "synthetic_v1"
MANIFEST_VERSION = "1.0.0"

DESCRIPTION = (
    "SYNTHETIC dataset generated by eval/datasets/generate_synthetic_dataset.py. "
    "Procedurally generated frames; no real faces, no real presentation attack "
    "instruments. NOT real-world PAD evidence."
)


def _base_face_frame(rng: np.random.Generator) -> np.ndarray:
    """Textured, colorful face-like frame (skin-tone ellipse + detail noise)."""
    frame = np.zeros((FRAME_H, FRAME_W, 3), dtype=np.uint8)
    # Background gradient
    gradient = np.linspace(40, 90, FRAME_W, dtype=np.uint8)
    frame[:, :, 0] = gradient[None, :]
    frame[:, :, 1] = gradient[None, :] // 2
    frame[:, :, 2] = gradient[None, :] // 3

    center = (FRAME_W // 2, FRAME_H // 2)
    axes = (int(FRAME_W * 0.22), int(FRAME_H * 0.36))
    skin_bgr = (
        int(rng.integers(90, 130)),
        int(rng.integers(130, 175)),
        int(rng.integers(180, 230)),
    )
    cv2.ellipse(frame, center, axes, 0, 0, 360, skin_bgr, -1)

    # Facial features (eyes, mouth) add local contrast
    eye_y = FRAME_H // 2 - axes[1] // 3
    for dx in (-axes[0] // 2, axes[0] // 2):
        cv2.circle(frame, (center[0] + dx, eye_y), 8, (30, 30, 30), -1)
    cv2.ellipse(
        frame,
        (center[0], center[1] + axes[1] // 2),
        (axes[0] // 2, 8),
        0, 0, 180, (40, 40, 90), 3,
    )

    # High-frequency detail (skin texture / sensor noise)
    noise = rng.normal(0, 18, frame.shape).astype(np.int16)
    frame = np.clip(frame.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    return frame


def _shift(frame: np.ndarray, dx: int, dy: int) -> np.ndarray:
    matrix = np.float32([[1, 0, dx], [0, 1, dy]])
    return cv2.warpAffine(
        frame, matrix, (FRAME_W, FRAME_H), borderMode=cv2.BORDER_REPLICATE
    )


def generate_bona_fide_clip(rng: np.random.Generator) -> list[np.ndarray]:
    """Live subject: texture + color + natural head motion between frames."""
    base = _base_face_frame(rng)
    frames = []
    drift = float(rng.uniform(3.0, 7.0))
    for index in range(FRAMES_PER_CLIP):
        dx = int(round(np.sin(index / 2.0) * drift * 4))
        dy = int(rng.integers(-2, 3))
        moved = _shift(base, dx, dy)
        # per-frame sensor noise so frames are not identical
        noise = rng.normal(0, 6, moved.shape).astype(np.int16)
        frames.append(
            np.clip(moved.astype(np.int16) + noise, 0, 255).astype(np.uint8)
        )
    return frames


def generate_print_attack_clip(rng: np.random.Generator) -> list[np.ndarray]:
    """PA-01: printed photo — blurred, desaturated, rigid (no motion)."""
    base = _base_face_frame(rng)
    printed = cv2.GaussianBlur(base, (9, 9), 4.0)
    gray = cv2.cvtColor(printed, cv2.COLOR_BGR2GRAY)
    printed = cv2.addWeighted(
        printed, 0.35, cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR), 0.65, 0
    )
    frames = []
    for _ in range(FRAMES_PER_CLIP):
        noise = rng.normal(0, 2, printed.shape).astype(np.int16)
        frames.append(
            np.clip(printed.astype(np.int16) + noise, 0, 255).astype(np.uint8)
        )
    return frames


def generate_screen_static_clip(rng: np.random.Generator) -> list[np.ndarray]:
    """PA-02: static image on a screen — flat, backlight glare, no motion."""
    base = _base_face_frame(rng)
    flat = cv2.GaussianBlur(base, (7, 7), 3.0)
    glare = np.full_like(flat, (int(rng.integers(30, 60)),) * 3)
    screen = cv2.addWeighted(flat, 0.75, glare, 0.25, 20)
    frames = []
    for _ in range(FRAMES_PER_CLIP):
        noise = rng.normal(0, 2, screen.shape).astype(np.int16)
        frames.append(
            np.clip(screen.astype(np.int16) + noise, 0, 255).astype(np.uint8)
        )
    return frames


def generate_screen_video_clip(rng: np.random.Generator) -> list[np.ndarray]:
    """PA-03: replayed video on a screen — motion present but flat texture."""
    base = _base_face_frame(rng)
    flat = cv2.GaussianBlur(base, (7, 7), 3.5)
    glare = np.full_like(flat, 45)
    screen = cv2.addWeighted(flat, 0.78, glare, 0.22, 15)
    frames = []
    drift = float(rng.uniform(2.0, 5.0))
    for index in range(FRAMES_PER_CLIP):
        dx = int(round(np.sin(index / 2.0) * drift * 3))
        moved = _shift(screen, dx, 0)
        noise = rng.normal(0, 2, moved.shape).astype(np.int16)
        frames.append(
            np.clip(moved.astype(np.int16) + noise, 0, 255).astype(np.uint8)
        )
    return frames


GENERATORS = {
    "BF": ("bona_fide", "bona_fide", generate_bona_fide_clip, 150),
    "PA-01": ("attack", "attacks/PA-01_print", generate_print_attack_clip, 50),
    "PA-02": ("attack", "attacks/PA-02_screen_static", generate_screen_static_clip, 50),
    "PA-03": ("attack", "attacks/PA-03_screen_video", generate_screen_video_clip, 50),
}


def write_clip(session_dir: Path, frames: list[np.ndarray]) -> None:
    session_dir.mkdir(parents=True, exist_ok=True)
    for index, frame in enumerate(frames, start=1):
        cv2.imwrite(str(session_dir / f"frame_{index:04d}.jpg"), frame)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=20260826)
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    root: Path = args.output_dir
    root.mkdir(parents=True, exist_ok=True)

    samples = []
    subject_counter = 0
    for pai_id, (ground_truth, subdir, generator, count) in GENERATORS.items():
        for index in range(1, count + 1):
            subject_id = f"synth_subj_{subject_counter % 30:03d}"
            subject_counter += 1
            rel_path = f"{subdir}/session_{index:03d}"
            write_clip(root / rel_path, generator(rng))
            samples.append(
                {
                    "sample_id": f"{pai_id.replace('-', '')}_{index:03d}",
                    "pai_id": pai_id,
                    "ground_truth": ground_truth,
                    "subject_id": subject_id,
                    "path": rel_path,
                    "presentation_type": "clip",
                    "capture_device": "synthetic",
                    "frame_count": FRAMES_PER_CLIP,
                }
            )

    manifest = {
        "manifest_version": MANIFEST_VERSION,
        "collection_id": COLLECTION_ID,
        "description": DESCRIPTION,
        "data_provenance": "SYNTHETIC",
        "generator": "eval/datasets/generate_synthetic_dataset.py",
        "seed": args.seed,
        "samples": samples,
    }
    manifest_path = root / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    (root / "README.md").write_text(
        "# SYNTHETIC PAD dataset\n\n"
        "Generated by `eval/datasets/generate_synthetic_dataset.py` "
        f"(seed {args.seed}).\n\n"
        "**This dataset is SYNTHETIC.** It contains no real faces and no real "
        "presentation attack instruments. Results obtained on it measure the "
        "evaluation harness and heuristic scorer behavior only, and are NOT "
        "real-world PAD evidence.\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(samples)} presentations to {root}")
    print(f"Manifest: {manifest_path}")


if __name__ == "__main__":
    main()
